"""RFC 6902 JSON Patch, applied to a copy of a document.

A transformer agent returns the few operations its instruction asks for and the
harness applies them to the input, so every value outside the patch stays
byte-identical by construction instead of being regenerated by the model.
"""

from __future__ import annotations

from copy import deepcopy
from typing import Any

_OPS = frozenset({"add", "remove", "replace", "move", "copy", "test"})
# The members an RFC 6902 operation is made of.  Any other key is refused, not
# ignored: a model that writes ``"_skip": true`` beside an operation expects it
# to mean something, and applying the operation anyway changes the document
# behind its back.
_OPERATION_KEYS = frozenset({"op", "path", "value", "from"})


class JsonPatchError(ValueError):
    """An operation that cannot be applied, named by its index in the patch."""


def _parse_pointer(pointer: object, index: int) -> list[str]:
    if not isinstance(pointer, str) or (pointer and not pointer.startswith("/")):
        raise JsonPatchError(f"op {index}: path {pointer!r} is not a JSON Pointer (it starts with '/').")
    if pointer == "":
        return []
    return [part.replace("~1", "/").replace("~0", "~") for part in pointer[1:].split("/")]


def _list_index(container: list[Any], segment: str, index: int, *, allow_end: bool) -> int:
    if segment == "-" and allow_end:
        return len(container)
    if not segment.isdigit() or (len(segment) > 1 and segment.startswith("0")):
        raise JsonPatchError(f"op {index}: '{segment}' is not an array index.")
    position = int(segment)
    limit = len(container) if allow_end else len(container) - 1
    if position > limit:
        raise JsonPatchError(f"op {index}: index {position} is out of range (array of {len(container)}).")
    return position


def _parent(doc: Any, parts: list[str], index: int) -> Any:
    node = doc
    for depth, segment in enumerate(parts[:-1]):
        if isinstance(node, dict):
            if segment not in node:
                raise JsonPatchError(f"op {index}: '/{'/'.join(parts[: depth + 1])}' does not exist.")
            node = node[segment]
        elif isinstance(node, list):
            node = node[_list_index(node, segment, index, allow_end=False)]
        else:
            raise JsonPatchError(f"op {index}: '/{'/'.join(parts[: depth + 1])}' is not an object or an array.")
    return node


def _get(doc: Any, parts: list[str], index: int) -> Any:
    if not parts:
        return doc
    parent = _parent(doc, parts, index)
    segment = parts[-1]
    if isinstance(parent, dict):
        if segment not in parent:
            raise JsonPatchError(f"op {index}: '/{'/'.join(parts)}' does not exist.")
        return parent[segment]
    if isinstance(parent, list):
        return parent[_list_index(parent, segment, index, allow_end=False)]
    raise JsonPatchError(f"op {index}: the parent of '/{'/'.join(parts)}' is not an object or an array.")


def _remove(doc: Any, parts: list[str], index: int) -> Any:
    if not parts:
        raise JsonPatchError(f"op {index}: the whole document cannot be removed.")
    parent = _parent(doc, parts, index)
    segment = parts[-1]
    if isinstance(parent, dict):
        if segment not in parent:
            raise JsonPatchError(f"op {index}: '/{'/'.join(parts)}' does not exist.")
        return parent.pop(segment)
    if isinstance(parent, list):
        return parent.pop(_list_index(parent, segment, index, allow_end=False))
    raise JsonPatchError(f"op {index}: the parent of '/{'/'.join(parts)}' is not an object or an array.")


def _add(doc: Any, parts: list[str], value: Any, index: int) -> Any:
    if not parts:
        return value
    parent = _parent(doc, parts, index)
    segment = parts[-1]
    if isinstance(parent, dict):
        parent[segment] = value
    elif isinstance(parent, list):
        parent.insert(_list_index(parent, segment, index, allow_end=True), value)
    else:
        raise JsonPatchError(f"op {index}: the parent of '/{'/'.join(parts)}' is not an object or an array.")
    return doc


def apply_json_patch(document: Any, patch: object) -> Any:
    """Return *document* with the RFC 6902 *patch* applied; *document* is not modified.

    Raises :class:`JsonPatchError` naming the first operation that cannot apply:
    the patch is all or nothing.  An operation carrying a key other than op,
    path, value and from is refused rather than applied with the key ignored.
    """
    if not isinstance(patch, list):
        raise JsonPatchError("the patch must be an array of operations.")
    doc = deepcopy(document)
    for index, operation in enumerate(patch):
        if not isinstance(operation, dict):
            raise JsonPatchError(f"op {index}: an operation is an object with 'op' and 'path'.")
        unknown = sorted(key for key in operation if key not in _OPERATION_KEYS)
        if unknown:
            raise JsonPatchError(
                f"op {index}: unknown key '{unknown[0]}' (an operation has only op, path, value and from)."
            )
        op = operation.get("op")
        if op not in _OPS:
            raise JsonPatchError(f"op {index}: 'op' must be one of {', '.join(sorted(_OPS))}.")
        parts = _parse_pointer(operation.get("path"), index)
        if op in {"add", "replace", "test"} and "value" not in operation:
            raise JsonPatchError(f"op {index}: '{op}' needs a 'value'.")
        if op == "add":
            doc = _add(doc, parts, deepcopy(operation["value"]), index)
        elif op == "remove":
            _remove(doc, parts, index)
        elif op == "replace":
            _get(doc, parts, index)
            if parts:
                _remove(doc, parts, index)
            doc = _add(doc, parts, deepcopy(operation["value"]), index)
        elif op == "test":
            if _get(doc, parts, index) != operation["value"]:
                raise JsonPatchError(f"op {index}: test failed at '{operation.get('path')}'.")
        else:  # move / copy
            source = _parse_pointer(operation.get("from"), index)
            if op == "move":
                if parts[: len(source)] == source and len(parts) > len(source):
                    raise JsonPatchError(f"op {index}: a value cannot be moved into itself.")
                value = _remove(doc, source, index)
            else:
                value = deepcopy(_get(doc, source, index))
            doc = _add(doc, parts, value, index)
    return doc
