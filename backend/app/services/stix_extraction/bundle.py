"""The extracted objects written as one STIX 2.1 bundle OpenCTI imports as is.

Every id is the STIX standard id OpenCTI derives (``stix_standard_id``), so re-running the
extraction or importing the bundle twice converges on the same objects, and an object the
platform already holds merges into it. Each object keeps where it was read: its mentions'
offsets in ``x_xtm_mentions`` (``[start, end]`` pairs into the extracted text) and each
relationship its evidence quote in ``description``, so an analyst can check any of them
against the source. A ``report`` names the document and refers to everything extracted.
"""

