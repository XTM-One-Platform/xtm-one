def _country_code(code: str, name: str = "") -> str | None:
    """The ISO 3166-1 alpha-2 code of a country given its alpha-2 or alpha-3 code, or
    OpenCTI's name of it; ``None`` when neither tells it."""
    countries = _countries()
    code = code.strip().upper()
    if code in countries:
        return code
    for alpha2, known in countries.items():
        if code and code == known["alpha3"]:
            return alpha2
    folded = " ".join(name.split()).casefold()
    for alpha2, known in countries.items():
        if folded and folded == known["name"].casefold():
            return alpha2
    return None


@cache
def _countries() -> dict[str, dict[str, str]]:
    """ISO 3166-1 alpha-2 → OpenCTI's country name and alpha-3 (its geography dataset,
    ``data/opencti_geography.json``, regenerated by ``scripts/stix_opencti_geography.py``)."""
    path = Path(__file__).with_name("data") / "opencti_geography.json"
    return json.loads(path.read_text(encoding="utf-8"))["countries"]
STATED_CONFIDENCE = 85
IMPLIED_CONFIDENCE = 50
#: An extracted object's confidence. OpenCTI matches an incoming object on its aliases
#: too, and an object without confidence upserts at the importing user's maximum: it
#: could then rename a curated object (a dataset's, at 100) it matched by alias.
OBJECT_CONFIDENCE = 75


@dataclass
class ExtractedObject:
    """One object of the extraction: kind, name, other names, where it was read."""

    ref: str
    kind: str
    name: str
    aliases: list[str] = field(default_factory=list)
    spans: list[tuple[int, int]] = field(default_factory=list)
    code: str = ""
    value: str = ""
    #: Identifiers in a knowledge base, ``(source_name, external_id)``: ATT&CK G/S/C ids.
    external_ids: list[tuple[str, str]] = field(default_factory=list)
    #: A product's vendor and version as the text writes them (STIX ``software``).
    vendor: str = ""
    version: str = ""
    #: A malware's types (``malware_types``, the malware-type vocabulary): ``ransomware``.
    malware_types: list[str] = field(default_factory=list)


@dataclass
class ExtractedRelation:
    """A relationship between two extracted objects, with its evidence quotes."""

    source: str
    type: str
    target: str
    evidence: list[str] = field(default_factory=list)
    implied: bool = False
    #: The numbered segments the evidence was read in (for verification).
    segments: list[int] = field(default_factory=list)
    #: A verifier's 0-1 confidence, when the relationship was verified.
    verified: float | None = None
    #: Its verb was remapped by the relationship matrix.
    remapped: bool = False
    #: "extraction", or "gleaning" for one a recall pass added.
    origin: str = "extraction"


def _region_code(value: str) -> str | None:
    """The STIX region vocabulary value closest to *value* ("south-asia", "South Asia"
    → ``southern-asia``), or ``None`` when none is close."""
    candidate = re.sub(r"[^a-z]+", "-", value.strip().lower()).strip("-")
    if candidate in REGION_VOCABULARY:
        return candidate
    close = difflib.get_close_matches(candidate, sorted(REGION_VOCABULARY), n=1, cutoff=0.8)
    return close[0] if close else None


#: Words that orient a place without naming one.
_DIRECTIONS = frozenset({"north", "south", "east", "west", "central", "northern", "southern", "eastern", "western",
                         "northeast", "northwest", "southeast", "southwest", "northeastern", "northwestern",
                         "southeastern", "southwestern", "and"})


def _names_region(name: str, region: str) -> bool:
    """Whether *name* is a spelling of the STIX *region* ("Southeast Asian", "East Asia",
    "Latin America"), not a place inside it ("CIS" or "Crimea" in ``eastern-europe``). A name
    of directions only ("South" from "South and East Asia") names no place: the region's."""
    words = re.findall(r"[a-z]+", name.lower())
    if words and all(w in _DIRECTIONS for w in words):
        return True
    candidate = re.sub(r"[^a-z]+", "-", name.strip().lower()).strip("-")
    return difflib.SequenceMatcher(None, candidate, region).ratio() >= 0.7


_MONTHS = {
    m: i + 1
    for i, names in enumerate(
        ("jan january", "feb february", "mar march", "apr april", "may", "jun june", "jul july",
         "aug august", "sep sept september", "oct october", "nov november", "dec december")
    )
    for m in names.split()
}
_MONTH = r"(?P<month>" + "|".join(sorted(_MONTHS, key=len, reverse=True)) + r")\.?"
_DATE_FORMS = (
    r"(?P<year>(?:19|20)\d{2})-(?P<mm>\d{2})-(?P<day>\d{2})",
    _MONTH + r"\s+(?P<day>\d{1,2})(?:st|nd|rd|th)?,?\s+(?P<year>(?:19|20)\d{2})",
    r"(?P<day>\d{1,2})(?:st|nd|rd|th)?\s+" + _MONTH + r",?\s+(?P<year>(?:19|20)\d{2})",
)
def default_report_name(text: str) -> str:
    """The name of a report whose document has none: "Extracted report" and a digest of
    its text. A report's standard id is its name and publication date, so two different
    unnamed texts extracted on one day must not share a name (OpenCTI would merge their
    reports), while the same text extracted again keeps its report."""
    return f"Extracted report {_text_digest(text)}"


def file_report_name(filename: str, text: str) -> str:
    """The name of a report read from a file with no title given: the file's name and a
    digest of its text. A file name does not tell two reports apart (two ``report.pdf``
    extracted on one day would share a standard id and OpenCTI would merge them), while
    the same file extracted again keeps its report."""
    return f"{filename} ({_text_digest(text)})"


def _text_digest(text: str) -> str:
    return hashlib.sha256(" ".join(text.split()).encode("utf-8")).hexdigest()[:12]


def published_date(text: str) -> datetime | None:
    """The date a report says it was published ("Published: March 5, 2024", "Date:
    2024-03-05"), read in its first lines; an update date only when no publication date
    is given. ``None`` when the report states none."""
    head = text[:4000]
    found: list[tuple[int, datetime]] = []
    for match in re.finditer(
        r"\b(published|publication date|posted|released|issued|date|last updated|updated)\b(?:\s+on)?\s*[:\-\u2013]?\s*",
        head,
        re.IGNORECASE,
    ):
        rest = head[match.end():match.end() + 40]
        for form in _DATE_FORMS:
            date = re.match(form, rest, re.IGNORECASE)
            if not date:
                continue
            parts = date.groupdict()
            month = int(parts["mm"]) if parts.get("mm") else _MONTHS.get(parts["month"].lower().rstrip("."), 0)
            try:
                moment = datetime(int(parts["year"]), month, int(parts["day"]), tzinfo=UTC)
            except ValueError:
                break
            rank = 1 if "updated" in match.group(1).lower() or match.group(1).lower() == "date" else 0
            found.append((rank, moment))
            break
    return min(found, key=lambda item: item[0])[1] if found else None


def _timestamp(moment: datetime) -> str:
    return f"{moment:%Y-%m-%dT%H:%M:%S}.{moment.microsecond // 1000:03d}Z"


def is_observable(obj: ExtractedObject) -> bool:
    """Whether the bundle writes *obj* as a STIX cyber observable (an SCO)."""
    return _observable(obj) is not None


def _observable(obj: ExtractedObject) -> dict | None:
    value = obj.value or obj.name
    hashes = {"md5": "MD5", "sha1": "SHA-1", "sha256": "SHA-256", "sha512": "SHA-512"}
    if obj.kind in hashes:
        return {"type": "file", "hashes": {hashes[obj.kind]: value}}
    if obj.kind == "mac-addr":
        return {"type": "mac-addr", "value": value}
    if obj.kind == "autonomous-system":
        return {"type": "autonomous-system", "number": int(value)}
    if obj.kind == "file-name":
        return {"type": "file", "name": value}
    if obj.kind == "windows-registry-key":
        return {"type": "windows-registry-key", "key": value}
    if obj.kind == "product":
        # A product a vulnerability is in: STIX's software observable (OpenCTI's Software).
        software = {"type": "software", "name": " ".join(obj.name.split())}
        if obj.vendor:
            software["vendor"] = obj.vendor
        if obj.version:
            software["version"] = obj.version
        return software
    if obj.kind in ("ipv4-addr", "ipv6-addr", "domain-name", "url", "email-addr"):
        return {"type": obj.kind, "value": value}
    return None


def _observable_id(data: dict) -> str:
    """The STIX 2.1 deterministic id of an observable (UUIDv5 over its id-contributing
    properties, computed by ``stix2``): what any STIX tool derives for the same value."""
    import stix2

    try:
        return str(stix2.parse(dict(data), allow_custom=True, version="2.1").id)
    except Exception:  # a value stix2 refuses keeps a standard id of the platform's
        return stix_standard_id(data) or f"{data['type']}--{uuid.uuid4()}"


#: Graded confidence: what the extraction has for an object beyond its being read in the
#: text, each worth some points over the floor, never above :data:`OBJECT_CONFIDENCE`.
_CONFIDENCE_FLOOR = 40


def object_confidence(obj: ExtractedObject, relations: Sequence[ExtractedRelation]) -> int:
    """An object's confidence from what supports it: an identifier a knowledge base or the
    text gives (an ATT&CK id, a CVE), several mentions, a relationship the text states (or
    only implies). An object read once, linked to nothing, sits at the floor; one with all
    of them at :data:`OBJECT_CONFIDENCE`, the ceiling that keeps it from overwriting a
    curated object OpenCTI holds."""
    stated = any(not r.implied for r in relations if obj.ref in (r.source, r.target))
    implied = any(r.implied for r in relations if obj.ref in (r.source, r.target))
    score = _CONFIDENCE_FLOOR
    if obj.external_ids or obj.kind in ("attack-pattern-id", "cve"):
        score += 15
    if len(set(obj.spans)) >= 2:
        score += 10
    score += 15 if stated else 5 if implied else 0
    return min(score, OBJECT_CONFIDENCE)


def _domain_object(obj: ExtractedObject, created: str) -> dict | None:
    shape = stix_shape(obj.kind)
    if shape is None:
        return None
    data: dict = {
        "type": shape.stix_type,
        "spec_version": "2.1",
        "created": created,
        "modified": created,
        "name": " ".join(obj.name.split()),
        "confidence": OBJECT_CONFIDENCE,
    }
    for key, value in shape.extra:
        data[key] = True if value == "true" else value
    if shape.stix_type == "malware" and obj.malware_types:
        data["malware_types"] = list(obj.malware_types)
    extra_aliases: list[str] = []
    if obj.kind == "attack-pattern-id":
        data["x_mitre_id"] = obj.value or obj.name
        data["external_references"] = [{"source_name": "mitre-attack", "external_id": data["x_mitre_id"]}]
    elif obj.kind == "cve":
        data["external_references"] = [{"source_name": "cve", "external_id": obj.name}]
    elif shape.stix_type == "location":
        code = obj.code.strip()
        region = _region_code(code) or _region_code(obj.name) if obj.kind == "region" else None
        if region:
            data["region"] = region
            # A location's standard id is its name: OpenCTI's own name merges into its
            # object ("Southeast Asia" is its "South-eastern Asia"). Only when the name is
            # that region: the code of a place inside it ("CIS", "Crimea", "New York" in
            # eastern-europe or northern-america) classifies it and does not rename it.
            if region in _REGION_NAMES and _names_region(obj.name, region):
                data["name"] = _REGION_NAMES[region]
        elif obj.kind in ("country", "city"):
            # ``country`` is an ISO 3166-1 alpha-2 code. A place whose country cannot be
            # told has none of the region, country or coordinates STIX requires: it is
            # left out rather than given its own name as a country.
            country = _country_code(code, obj.name if obj.kind == "country" else "")
            if country is None:
                return None
            data["country"] = country
            known = _countries().get(country)
            if obj.kind == "country" and known:
                # "Russia", "Russian" and "RU" are OpenCTI's "Russian Federation", whose
                # aliases are its ISO codes.
                data["name"] = known["name"]
                extra_aliases = [obj.name, country, known["alpha3"]]
        else:
            # STIX requires a region, a country or coordinates; a region's name is in the
            # region vocabulary's open form.
            data["region"] = obj.name
    if obj.external_ids and "external_references" not in data:
        data["external_references"] = [
            {"source_name": source, "external_id": external_id} for source, external_id in obj.external_ids
        ]
    aliases = [
        " ".join(alias.split())
        for alias in dict.fromkeys([*obj.aliases, *extra_aliases, *([obj.name] if data["name"] != obj.name else [])])
        if alias and alias != data["name"]
    ]
    if aliases:
        data[_ALIASES_PROPERTY.get(shape.stix_type, "x_opencti_aliases")] = aliases
    return data


# OpenCTI's name of each observable type, for an indicator's main observable type.
_OBSERVABLE_TYPE_NAMES = {
    "ipv4-addr": "IPv4-Addr",
    "ipv6-addr": "IPv6-Addr",
    "domain-name": "Domain-Name",
    "url": "Url",
    "email-addr": "Email-Addr",
    "file": "StixFile",
    "mac-addr": "Mac-Addr",
    "autonomous-system": "Autonomous-System",
    "windows-registry-key": "Windows-Registry-Key",
}
#: STIX types an indicator may indicate (OpenCTI's schema).
_INDICATED_TYPES = frozenset({"malware", "tool", "intrusion-set", "threat-actor", "campaign", "infrastructure"})


def _pattern(observable: dict) -> tuple[str, str] | None:
    """The STIX pattern of an observable, and the value it shows as the indicator's name."""

    def literal(value: object) -> str:
        return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"

    kind = observable["type"]
    if kind == "file":
        hashes = observable.get("hashes") or {}
        if hashes:
            algorithm, value = next(iter(hashes.items()))
            return f"[file:hashes.'{algorithm}' = {literal(value)}]", str(value)
        return f"[file:name = {literal(observable['name'])}]", str(observable["name"])
    if kind == "autonomous-system":
        return f"[autonomous-system:number = {int(observable['number'])}]", f"AS{observable['number']}"
    if kind == "windows-registry-key":
        return f"[windows-registry-key:key = {literal(observable['key'])}]", str(observable["key"])
    if "value" in observable:
        return f"[{kind}:value = {literal(observable['value'])}]", str(observable["value"])
    return None


def _indicator(observable: dict, created: str) -> dict | None:
    pattern = _pattern(observable)
    if pattern is None:
        return None
    data = {
        "type": "indicator",
        "spec_version": "2.1",
        "created": created,
        "modified": created,
        "name": pattern[1],
        "pattern": pattern[0],
        "pattern_type": "stix",
        "valid_from": created,
        "indicator_types": ["malicious-activity"],
        "x_opencti_main_observable_type": _OBSERVABLE_TYPE_NAMES.get(observable["type"], observable["type"]),
    }
    data["id"] = stix_standard_id(data) or f"indicator--{uuid.uuid4()}"
    return data


def build_bundle(
    objects: Sequence[ExtractedObject],
    relations: Sequence[ExtractedRelation],
    *,
    document_name: str,
    include_report: bool = True,
    include_evidence: bool = True,
    now: datetime | None = None,
    references: Sequence[str] = (),
    published: datetime | None = None,
    author: str = "",
    graded_confidence: bool = False,
) -> dict:
    """The STIX 2.1 bundle of the extraction (objects, relationships and a report, which
    keeps the links the document cites as its external references). *author*, the
    organization that published the document, is the report's ``created_by_ref`` identity,
    as OpenCTI records a report's source."""
    created = _timestamp(now or datetime.now(UTC))
    stix_objects: list[dict] = []
    ids: dict[str, str] = {}
    built: dict[str, dict] = {}
    for obj in objects:
        data = _observable(obj)
        if data is not None:
            data["spec_version"] = "2.1"
            stix_id = _observable_id(data)
        else:
            data = _domain_object(obj, created)
            if data is None:
                continue
            stix_id = stix_standard_id(data) or f"{data['type']}--{uuid.uuid4()}"
        ids[obj.ref] = stix_id
        kept = built.get(stix_id)
        if kept is not None:
            # Two extracted objects, one STIX object: one is enough, with both one's mentions.
            if include_evidence and obj.spans:
                mentions = {tuple(span) for span in kept.get("x_xtm_mentions", [])} | set(obj.spans)
                kept["x_xtm_mentions"] = [[start, end] for start, end in sorted(mentions)]
            continue
        data["id"] = stix_id
        if include_evidence and obj.spans:
            data["x_xtm_mentions"] = [[start, end] for start, end in sorted(set(obj.spans))]
        if graded_confidence and "confidence" in data:
            data["confidence"] = object_confidence(obj, relations)
        built[stix_id] = data
        stix_objects.append(data)

    by_id = {data["id"]: data for data in stix_objects}
    seen: set[tuple[str, str, str]] = set()
    indicators: dict[str, str] = {}

    def link(source: str, verb: str, target: str, relation: ExtractedRelation | None) -> None:
        key = (source, verb, target)
        if key in seen:
            return
        seen.add(key)
        data = {
            "type": "relationship",
            "spec_version": "2.1",
            "created": created,
            "modified": created,
            "relationship_type": verb,
            "source_ref": source,
            "target_ref": target,
        }
        if relation is not None:
            # A verifier's score when there is one, else stated or only implied by the
            # text (OpenCTI's 0-100 scale).
            data["confidence"] = (
                round(relation.verified * 100) if relation.verified is not None
                else IMPLIED_CONFIDENCE if relation.implied else STATED_CONFIDENCE
            )
            if include_evidence and relation.evidence:
                data["description"] = " […] ".join(dict.fromkeys(relation.evidence))[:2000]
            # The step that read it (a chunk's reading, a candidate pair, the page's layout, a
            # behaviour...): what an analyst or an evaluation weighs a relationship by.
            data["x_xtm_origin"] = relation.origin
        data["id"] = stix_standard_id(data) or f"relationship--{uuid.uuid4()}"
        stix_objects.append(data)

    def indicator_of(observable_id: str) -> str | None:
        """The indicator based on an observable, created once (OpenCTI detects with an
        indicator, and links an observable to a threat through it)."""
        if observable_id not in indicators:
            data = _indicator(by_id[observable_id], created)
            if data is None:
                return None
            indicators[observable_id] = data["id"]
            stix_objects.append(data)
            link(data["id"], "based-on", observable_id, None)
        return indicators[observable_id]

    for relation in relations:
        source, target = ids.get(relation.source), ids.get(relation.target)
        if not source or not target or source == target:
            continue
        if relation.type != "indicates":
            link(source, relation.type, target, relation)
        # An observable tied to a threat (its C2, its sample, a file it drops) is what an
        # indicator of that threat is based on.
        observable = next((ref for ref in (source, target) if by_id[ref]["type"] in _OBSERVABLE_TYPE_NAMES), None)
        threat = next((ref for ref in (source, target) if by_id[ref]["type"] in _INDICATED_TYPES), None)
        if observable and threat:
            indicator = indicator_of(observable)
            if indicator:
                link(indicator, "indicates", threat, relation)

    if include_report and stix_objects:
        report = {
            "type": "report",
            "spec_version": "2.1",
            "created": created,
            "modified": created,
            "name": document_name or "Extracted report",
            # A report's standard id is its name and publication date: the date the
            # document states, else the day of the extraction (never the instant), so an
            # extraction run again converges on one report.
            "published": _timestamp(published or (now or datetime.now(UTC)).replace(hour=0, minute=0, second=0, microsecond=0)),
            "report_types": ["threat-report"],
            "object_refs": [obj["id"] for obj in stix_objects],
        }
        if references:
            report["external_references"] = [{"source_name": "cited", "url": url} for url in references[:100]]
        if author.strip():
            source = {"type": "identity", "spec_version": "2.1", "created": created, "modified": created,
                      "name": " ".join(author.split()), "identity_class": "organization", "confidence": OBJECT_CONFIDENCE}
            source["id"] = stix_standard_id(source) or f"identity--{uuid.uuid4()}"
            if source["id"] not in {obj["id"] for obj in stix_objects}:
                stix_objects.append(source)
            report["created_by_ref"] = source["id"]
            report["object_refs"] = list(dict.fromkeys([*report["object_refs"], source["id"]]))
        report["id"] = stix_standard_id(report) or f"report--{uuid.uuid4()}"
        stix_objects.append(report)

    return {"type": "bundle", "id": f"bundle--{uuid.uuid4()}", "objects": stix_objects}


