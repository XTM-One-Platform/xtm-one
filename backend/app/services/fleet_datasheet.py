def build_datasheet_html(
    *,
    fleet_name: str,
    product_name: str,
    sections: dict[str, str],
    structured: dict[str, Any] | None,
    version: int,
    status: str,
    automations_on: int,
    automations_total: int,
    nodes: Sequence[GraphNode],
    prerequisites: Iterable[PrerequisiteLine],
    generated_on: datetime,
    author: str = AUTHOR_LABELS["ai"],
    tool_uses: Sequence[dict[str, Any]] | None = None,
    tool_labels: dict[str, str] | None = None,
    value: ValueFigures | None = None,
) -> str:
    """The datasheet as one HTML document: A4, light, capped to fit one page.

    *author* is :func:`datasheet_author`'s line; *tool_uses* the members' live
    bindings (``fleet_doc_generation.tool_use_facts``), preferred to the
    documentation's own list; *tool_labels* the catalog display name of each
    tool group and provider key (:func:`tool_label`); *value* the fleet's
    value over :data:`VALUE_WINDOW_DAYS` days (:func:`value_figures`), ``None``
    when its report could not be read (the sheet says so, never 0).
    """
    parts = structured or {}
    # The About page's order (#10123): status and figures first, then the graph beside the steps, the
    # member cards, then what starts it beside what it creates. No outcome or unit-of-work prose: the
    # ROI tab holds them.
    purpose = plain_text(parts.get("purpose_line") or sections.get("purpose"))
    status_key = status if status in STATUS_LABELS else "not_set_up"
    prereqs = list(prerequisites)
    met = sum(1 for p in prereqs if p.met)
    body = f"""
<div class="sheet">
  <header class="hero">
    <div class="product">{_e(product_name)} fleet datasheet</div>
    <h1>{_e(plain_text(fleet_name, 90))}<span class="status {status_key}">{_e(STATUS_LABELS[status_key])}</span></h1>
    <p class="lead">{_e(purpose) if purpose else MISSING}</p>
    {_serves(parts)}
  </header>
  <div class="kpis">
    <div class="kpi"><b>{_e(STATUS_LABELS[status_key])}</b>status</div>
    <div class="kpi"><b>{automations_on} of {automations_total}</b>automations on</div>
    <div class="kpi"><b>{_e(quota_text(parts))}</b>quota</div>
    <div class="kpi"><b>{met} of {len(prereqs)}</b>prerequisites met</div>
  </div>
  <div class="grid">
    <section><h2>Members</h2>{mini_graph_svg(nodes)}</section>
    <section><h2>How it works</h2>{_steps(parts)}</section>
    <section class="wide"><h2>Member cards</h2>{_member_cards(parts, tool_uses, tool_labels)}</section>
    <section><h2>What starts it</h2>{_triggers(parts)}</section>
    <section><h2>Objects it creates</h2>{_objects(parts)}</section>
    <section class="wide"><h2>Prerequisites</h2>{_prerequisites(prereqs)}</section>
    <section class="wide"><h2>Value, last {VALUE_WINDOW_DAYS} days</h2>{_value(value)}</section>
  </div>
  <footer><span>Generated on {_e(generated_on.strftime("%d %b %Y"))}, version {int(version)}</span>
  <span>{_e(author)}</span></footer>
</div>"""
    return (
        '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">'
        f"<title>{_e(plain_text(fleet_name, 90))} datasheet</title><style>{DATASHEET_STYLE}</style></head>"
        f"<body>{body}</body></html>"
    )


def datasheet_filename(fleet_name: str) -> str:
    """``<fleet-name>-datasheet.pdf``, lower case, safe characters only."""
    slug = re.sub(r"[^a-z0-9]+", "-", (fleet_name or "fleet").lower()).strip("-")[:60] or "fleet"
    return f"{slug}-datasheet.pdf"
