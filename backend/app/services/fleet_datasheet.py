def module_label(module: Any) -> str:
    """The name a module prints as (#9979): a base module's label, else the integration catalog's provider name.

    Never remapped to "Platform": an unknown key prints humanized.
    """
    key = str(module or "platform").strip().lower()
    if key in MODULE_LABELS:
        return MODULE_LABELS[key]
    from app.api.v1.integration_catalog import PROVIDER_CATALOG

    entry = PROVIDER_CATALOG.get(key)
    if isinstance(entry, dict) and entry.get("name"):
        return str(entry["name"])
    return key.replace("_", " ").capitalize()


