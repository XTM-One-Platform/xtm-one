"""A fleet's one-page datasheet (#9768 S4): its documentation as an A4 PDF.

The About page's "Export PDF" button (``GET /fleets/{id}/documentation/datasheet.pdf``)
hands someone presenting a fleet one page to share: hero (name, product,
purpose and outcome lines, status), a fixed mini graph of the members, the
triggers, the steps with their gates, the integrations and tools, the objects
by module, the live prerequisites, the quota range, the unit of work, and
"Generated on <date>, version N".

Rules:

* **No model call, no quota.** Everything comes from the stored documentation
  (``fleets.documentation``, the generator's output) and live state read by the
  route (automation counts, prerequisite checks, the member tree). Works with
  AI switched off and on a Community Edition: only the licence gate applies.
* **One page, always.** Every list is capped (:data:`CAPS`) and ends with
  "+N more" when cut; every text is cut at :data:`TEXT_CAP` characters. The
  renderer prints page 1 only (``page_ranges="1"``), so a dense fleet loses its
  tail, never gains a second page.
* **Print light.** One light palette whatever the reader's theme.
* **Never invent.** A part the documentation does not hold reads "Not stated
  in the documentation", never a guess.
* **Escaped.** Every value is HTML-escaped; the renderer runs with JavaScript
  off and the network blocked (:func:`app.services.pdf_render.render_text_to_pdf`).
"""

