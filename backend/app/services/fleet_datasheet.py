@dataclass(frozen=True)
class ValueFigures:
    """The fleet's value over :data:`VALUE_WINDOW_DAYS` days (#9836 R6d), from the ROI ledger (#12077 L4b).

    The same numbers as the ``figures`` of ``GET /roi?scope=fleet&id=`` for the
    window and the same reader: the route reads them through ``roi_ledger.figures``
    (invariant d). ``cost_masked`` hides the net value ("Hidden by your
    administrator", never 0). ``deliverables`` are the counted chat deliverables
    the hero includes (design 12.4: one total, automation and chat).
    """

    currency: str
    runs: int
    units: int
    hours_saved: float
    hours_saved_range: tuple[float, float]
    value: float
    value_range: tuple[float, float]
    net_value: float
    net_value_range: tuple[float, float]
    cost_masked: bool = False
    deliverables: int = 0
    #: k when the fleet is backed by fewer than k people for this reader (12.5): the block is hidden.
    under_k: int | None = None


def ledger_value_figures(figures: Any) -> ValueFigures:
    """A :class:`ValueFigures` from the ledger's ``roi_figures.Figures`` of the fleet (#12077 L4b).

    Reads the hero (``totals``) as ``Figures.as_dict`` answers it, so the sheet prints the
    figures ``GET /roi`` answers under ``figures.totals``; masked, the net reads hidden, never 0.
    Under k (``suppressed.own_share_only``, #12077 L7b), the totals are the reader's own share:
    ``under_k`` carries k and the sheet hides the block, as design 12.10 says.
    """
    answer = figures.as_dict()
    hero = answer["totals"]
    masked = bool(figures.cost_masked)
    suppressed = answer.get("suppressed") or {}

    def amount(key: str) -> float:
        return 0.0 if masked or hero.get(key) is None else float(hero[key])

    return ValueFigures(
        currency=str(figures.currency),
        runs=int(hero["runs"]),
        units=int(hero["units"]),
        hours_saved=float(hero["hours"]),
        hours_saved_range=(float(hero["hours_low"]), float(hero["hours_high"])),
        value=float(hero["value"]),
        value_range=(float(hero["value_low"]), float(hero["value_high"])),
        net_value=amount("net_value"),
        net_value_range=(amount("net_value_low"), amount("net_value_high")),
        cost_masked=masked,
        deliverables=int(hero["deliverables"]),
        under_k=int(suppressed["k"]) if suppressed.get("own_share_only") else None,
    )


def value_figures(figures: Any, *, cost_masked: bool) -> ValueFigures:
    """A :class:`ValueFigures` from a report's ``roi.RoiFigures`` (the shape before the ledger, kept for tests)."""
    return ValueFigures(
        currency=figures.currency,
        runs=int(figures.runs),
        units=int(figures.units),
        hours_saved=float(figures.hours_saved),
        hours_saved_range=(float(figures.hours_saved_low), float(figures.hours_saved_high)),
        value=float(figures.value),
        value_range=(float(figures.value_low), float(figures.value_high)),
        net_value=float(figures.net_value),
        net_value_range=(float(figures.net_value_low), float(figures.net_value_high)),
        cost_masked=cost_masked,
    )


def datasheet_author(updated_by: str | None, restored_from: dict[str, Any] | None = None) -> str:
    """Who wrote the documentation, as the About page says it (UX round 1 B4).

    A shipped seed reads "Written by Filigran", a fork's copy "Copied from the
    original fleet", a restore names the version it brought back; anything
    else was generated by AI.
    """
    if isinstance(restored_from, dict) and restored_from.get("author") in ("seed", "fork", "ai"):
        version = restored_from.get("version")
        if not version:
            return RESTORED_LABELS["shipped"]
        return RESTORED_LABELS[str(restored_from["author"])].format(source=int(version))
    if updated_by in ("seed", "fork"):
        return AUTHOR_LABELS[updated_by]
    return AUTHOR_LABELS["ai"]


def datasheet_status(total: int, enabled: int, paused: int) -> str:
    """The fleet's status from its automations, as the About hero says it.

    None on and none ever paused is Not set up; none on after a pause is
    Paused; some on is Partially on; every one on is On.
    """
    if enabled <= 0:
        return "paused" if total > 0 and paused > 0 else "not_set_up"
    return "partially_on" if enabled < total else "on"


def plain_text(markdown: str | None, cap: int = TEXT_CAP) -> str:
    """A markdown text as one plain line, cut at *cap* characters (an ellipsis marks the cut)."""
    text = markdown or ""
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"^\s{0,3}(#{1,6}|>|[-*+]|\d+[.)])\s+", "", text, flags=re.MULTILINE)
    text = re.sub(r"[*_`]+", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= cap:
        return text
    return text[: cap - 1].rstrip() + "\u2026"


def first_sentence(markdown: str | None, cap: int = TEXT_CAP) -> str:
    """The first sentence of a markdown text, as plain text cut at *cap* (#10327: a step body on the one-page sheet)."""
    text = plain_text(markdown, cap=10_000)
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return plain_text(match.group(1) if match else text, cap)


def _cap(items: Sequence[Any], key: str) -> tuple[list[Any], int]:
    limit = CAPS[key]
    return list(items[:limit]), max(0, len(items) - limit)


def _e(value: Any) -> str:
    return html.escape(str(value), quote=True)


def _more(count: int) -> str:
    return f'<li class="more">+{count} more</li>' if count else ""


def _missing() -> str:
    return f'<p class="missing">{MISSING}</p>'


def quota_range(structured: dict[str, Any]) -> tuple[int, int] | None:
    """The monthly run range summed over the quota lines, or None without any."""
    lines = [q for q in structured.get("quota") or [] if isinstance(q, dict)]
    if not lines:
        return None
    low = sum(int(q.get("runs_min") or 0) for q in lines)
    high = sum(int(q.get("runs_max") or 0) for q in lines)
    return low, max(low, high)


def name_lines(name: str, limit: int = NODE_LINE_CHARS) -> list[str]:
    """A node name wrapped on words into lines of at most *limit* characters.

    The whole name is kept (UX round 1 B2: no truncated label); a word longer
    than a line is split across lines rather than cut.
    """
    words = (plain_text(name, 10_000) or "Agent").split(" ")
    lines: list[str] = []
    current = ""
    for word in words:
        while len(word) > limit:
            if current:
                lines.append(current)
                current = ""
            lines.append(word[:limit])
            word = word[limit:]
        candidate = f"{current} {word}" if current else word
        if len(candidate) <= limit:
            current = candidate
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def mini_graph_svg(nodes: Sequence[GraphNode], *, width: int = 330, height: int = 170) -> str:
    """The fleet's members as a fixed left-to-right tree: one column per depth.

    Drawn, not laid out by forces: the same input gives the same picture.
    Every name is printed whole, wrapped inside its box, and every box sits
    inside the viewBox (the picture grows taller when a column needs it).
    Past :data:`CAPS` ``graph`` members, the deepest ones are dropped and a
    "+N more" label says how many.
    """
    if not nodes:
        return _missing()
    shown, hidden = _cap(sorted(nodes, key=lambda n: n.depth), "graph")
    kept = {n.agent_id for n in shown}
    columns: dict[int, list[GraphNode]] = {}
    for node in shown:
        columns.setdefault(node.depth, []).append(node)
    depths = sorted(columns)
    pad, line_h, gap = 4, 9.5, 6
    box_w = int(NODE_LINE_CHARS * NODE_CHAR_WIDTH + 2 * pad)
    lines = {n.agent_id: name_lines(n.name) for n in shown}
    box_h = {key: len(value) * line_h + 2 * pad for key, value in lines.items()}
    more_h = 12 if hidden else 0
    tallest = max(sum(box_h[n.agent_id] for n in col) + gap * (len(col) + 1) for col in columns.values())
    height = int(max(height, tallest + more_h) + 0.999)
    col_gap = (width - box_w) / (len(depths) - 1) if len(depths) > 1 else 0
    pos: dict[uuid.UUID, tuple[float, float]] = {}
    for index, depth in enumerate(depths):
        column = columns[depth]
        used = sum(box_h[n.agent_id] for n in column)
        spare = (height - more_h - used) / (len(column) + 1)
        x = index * col_gap if len(depths) > 1 else (width - box_w) / 2
        y = spare
        for node in column:
            pos[node.agent_id] = (x, y)
            y += box_h[node.agent_id] + spare
    edges: list[str] = []
    for node in shown:
        parent = node.parent_agent_id
        if parent is None or parent not in kept or node.agent_id not in pos:
            continue
        px, py = pos[parent]
        cx, cy = pos[node.agent_id]
        x1, y1 = px + box_w, py + box_h[parent] / 2
        x2, y2 = cx, cy + box_h[node.agent_id] / 2
        mid = (x1 + x2) / 2
        edges.append(
            f'<path d="M{x1:.1f},{y1:.1f} C{mid:.1f},{y1:.1f} {mid:.1f},{y2:.1f} {x2:.1f},{y2:.1f}" '
            'fill="none" stroke="#a5b0c4" stroke-width="1.2"/>'
        )
    boxes: list[str] = []
    for node in shown:
        x, y = pos[node.agent_id]
        fill, stroke, weight = ("#ede7fb", "#5e1ad5", "600") if node.is_orchestrator else ("#ffffff", "#c3cad8", "400")
        spans = "".join(
            f'<tspan x="{x + box_w / 2:.1f}" y="{y + pad + line_h * (row + 1) - 2.5:.1f}">{_e(text)}</tspan>'
            for row, text in enumerate(lines[node.agent_id])
        )
        boxes.append(
            f'<rect x="{x:.1f}" y="{y:.1f}" width="{box_w}" height="{box_h[node.agent_id]:.1f}" rx="5" '
            f'fill="{fill}" stroke="{stroke}"/>'
            f'<text text-anchor="middle" font-size="8" font-weight="{weight}" fill="#1b2333">{spans}</text>'
        )
    more = (
        f'<text x="{width - 2}" y="{height - 2}" text-anchor="end" font-size="8.5" fill="#5b6478">+{hidden} more</text>'
        if hidden
        else ""
    )
    return (
        f'<svg class="graph" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
        f'role="img" aria-label="Members of the fleet">{"".join(edges)}{"".join(boxes)}{more}</svg>'
    )


#: A work item key (``ns:part:...``) or a cron expression: machine text a reader never sees on the sheet.
MACHINE_DETAIL = re.compile(
    r"\b[a-z][a-z0-9_-]*:[a-z0-9_-]*:|(?:^|\s)[\d*/,-]+(?:\s+[\d*/,-]+){4}(?:\s|$)", re.IGNORECASE
)


def reader_detail(text: Any, cap: int = 120) -> str:
    """*text* as one plain line, or ``""`` when it names a work item key or a cron expression."""
    line = plain_text(str(text or ""), cap)
    return "" if MACHINE_DETAIL.search(line) else line


def _triggers(structured: dict[str, Any]) -> str:
    items = [t for t in structured.get("triggers") or [] if isinstance(t, dict)]
    if not items:
        return _missing()
    shown, hidden = _cap(items, "triggers")
    rows = "".join(
        f'<li><span class="tag">{_e(module_label(t.get("module")))}</span>'
        f"<b>{_e(plain_text(t.get('name'), 80))}</b>"
        + (f' <span class="dim">{_e(detail)}</span>' if (detail := reader_detail(t.get("detail"))) else "")
        + "</li>"
        for t in shown
    )
    return f"<ul>{rows}{_more(hidden)}</ul>"


def _steps(structured: dict[str, Any]) -> str:
    items = [s for s in structured.get("steps") or [] if isinstance(s, dict)]
    if not items:
        return _missing()
    shown, hidden = _cap(items, "steps")
    rows = "".join(
        f"<li><b>{_e(plain_text(s.get('title'), 80))}</b>"
        + (' <span class="gate">Approval gate</span>' if s.get("gate") else "")
        + (f'<br><span class="dim">{_e(first_sentence(s.get("detail"), 140))}</span>' if s.get("detail") else "")
        + "</li>"
        for s in shown
    )
    return f'<ol class="steps">{rows}{_more(hidden)}</ol>'


def tool_label(key: Any, labels: dict[str, str] | None = None) -> str:
    """The name a reader knows for a tool group, provider, MCP server or skill (UX round 2 B1).

    *labels* maps a catalog key (``generate_file``, ``mitre_atlas``) to its display
    name; a module key reads as its mark; any other key is humanized
    (``web_fetch`` -> ``Web fetch``), never printed raw.
    """
    text = str(key).strip()
    lowered = text.lower()
    if labels and lowered in labels:
        return labels[lowered]
    if lowered in MODULE_LABELS:
        return MODULE_LABELS[lowered]
    if re.fullmatch(r"[a-z0-9]+(?:[_-][a-z0-9]+)+", text):
        words = re.split(r"[_-]", text)
        return " ".join([words[0].capitalize(), *words[1:]])
    return text


def _clip(text: str, cap: int) -> str:
    """*text* cut at *cap* characters with an ellipsis; nothing else changed (names keep their underscores)."""
    return text if len(text) <= cap else text[: cap - 1].rstrip() + "\u2026"


def _member_cards(
    structured: dict[str, Any],
    live: Sequence[dict[str, Any]] | None = None,
    labels: dict[str, str] | None = None,
) -> str:
    """One equal card per member (#10123): name, one-line role, its integrations and tools (+N).

    The members come from the live bindings (UX round 1 B3), else the
    documentation's integrations, else its member roles; the role line is the
    documentation's ``members`` entry of the same name. Names print as their
    catalog display names (:func:`tool_label`), never through
    :func:`plain_text`, whose markdown stripper ate the underscores of raw keys
    (UX round 2 B1).
    """
    roles = {
        str(m.get("name") or "").strip().lower(): str(m.get("role") or "")
        for m in structured.get("members") or []
        if isinstance(m, dict)
    }
    used = [u for u in live or [] if isinstance(u, dict) and u.get("member")]
    items = (
        used
        or [i for i in structured.get("integrations") or [] if isinstance(i, dict) and i.get("member")]
        or [{"member": m.get("name")} for m in structured.get("members") or [] if isinstance(m, dict) and m.get("name")]
    )
    if not items:
        return _missing()
    shown, hidden = _cap(items, "cards")
    cards = []
    for use in shown:
        member = str(use.get("member") or "")
        names: list[str] = []
        for key in TOOL_KINDS:
            names.extend(tool_label(n, labels) for n in use.get(key) or [] if str(n).strip())
        names = list(dict.fromkeys(names))
        tools, more = names[: CAPS["card_tools"]], max(0, len(names) - CAPS["card_tools"])
        chips = "".join(f'<span class="tag">{_e(_clip(n, 28))}</span>' for n in tools)
        if more:
            chips += f'<span class="tag">+{more}</span>'
        if not chips:
            chips = '<span class="dim">no tools</span>'
        role = plain_text(roles.get(member.strip().lower()), 90)
        cards.append(
            f'<div class="card"><b>{_e(plain_text(member, 60))}</b>'
            + (f'<span class="dim role">{_e(role)}</span>' if role else "")
            + f'<span class="chips">{chips}</span></div>'
        )
    if hidden:
        cards.append(f'<div class="card more">+{hidden} more</div>')
    return f'<div class="cards">{"".join(cards)}</div>'


#: The compact units of a figure of 1,000 or more, as the screens write them (``roundForCompact`` in number-format.ts).
COMPACT_UNITS: tuple[tuple[Decimal, str], ...] = (
    (Decimal(1_000), "K"),
    (Decimal(1_000_000), "M"),
    (Decimal(1_000_000_000), "B"),
    (Decimal(1_000_000_000_000), "T"),
)


def _half_up(amount: Decimal, digits: int) -> Decimal:
    return amount.quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP)


def compact_figure(value: float | int) -> str | None:
    """A figure of 1,000 or more once rounded, compact as the screens draw it (#10476), else ``None``.

    At most 3 significant digits and 1 decimal on its unit: 1,238 reads "1.2K",
    316,151 "316K", 999,950 "1M" (never "1000K"), -40,522 "-40.5K". A figure
    under 1,000 is the caller's own form ("921", "7.5 h"). The page is printed,
    so the exact figure stays in the fleet's ROI report and its CSV export.
    """
    magnitude = abs(Decimal(repr(float(value))))
    if _half_up(magnitude, 1) < 1_000:
        return None
    sign = "-" if value < 0 else ""
    for unit, letter in COMPACT_UNITS:
        scaled = magnitude / unit
        rounded = _half_up(scaled, 0 if scaled >= 100 else 1)
        if rounded < 1_000 or letter == COMPACT_UNITS[-1][1]:
            text = f"{rounded:f}"
            text = text.rstrip("0").rstrip(".") if "." in text else text
            return f"{sign}{text}{letter}"
    return None  # pragma: no cover - the last unit always answers


def _count(value: int) -> str:
    """A count: "921", "1.2K", "3.5M"."""
    return compact_figure(value) or f"{value:,}"


def quota_text(structured: dict[str, Any]) -> str:
    """The monthly quota estimate in one number format (#10108): "about N" when the range is one value (#10123).

    Compact from 1,000 as the About page draws it (#10476): "about 1.2K", "40 to 2.5K".
    """
    quota = quota_range(structured)
    if not quota:
        return MISSING
    open_ended = any(isinstance(q, dict) and q.get("open_ended") for q in structured.get("quota") or [])
    # An event-driven trigger makes the range a floor, said so.
    if open_ended:
        return f"{_count(quota[1])} or more runs a month (estimate)"
    if quota[0] == quota[1]:
        return f"about {_count(quota[0])} runs a month (estimate)"
    return f"{_count(quota[0])} to {_count(quota[1])} runs a month (estimate)"


def _serves(structured: dict[str, Any]) -> str:
    items = [str(s).strip() for s in structured.get("serves") or [] if str(s).strip()]
    if not items:
        return ""
    shown, hidden = _cap(items, "serves")
    chips = "".join(f'<span class="tag">{_e(plain_text(s, 40))}</span>' for s in shown)
    more = f'<span class="tag">+{hidden}</span>' if hidden else ""
    return f'<p class="serves">Serves {chips}{more}</p>'


def _objects(structured: dict[str, Any]) -> str:
    items = [o for o in structured.get("objects") or [] if isinstance(o, dict)]
    if not items:
        return _missing()
    shown, hidden = _cap(items, "objects")
    rows = "".join(
        f'<li><span class="tag">{_e(module_label(o.get("module")))}</span>'
        f"{_e(plain_text(', '.join(str(x) for x in o.get('objects') or []), 150))}</li>"
        for o in shown
    )
    return f"<ul>{rows}{_more(hidden)}</ul>"


def _hours(amount: float) -> str:
    """Hours to one decimal, rounded half up from the decimal value (2.55 -> 2.6), as the screens.

    Compact from 1,000 (#10476): 1,234.45 h reads "1.2K h".
    """
    rounded = Decimal(str(amount)).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)
    compact = compact_figure(float(rounded))
    return f"{compact} h" if compact else f"{rounded:,.1f} h"


def _amount(amount: float, currency: str) -> str:
    """An amount in whole units, compact from 1,000 (#10476): "600 EUR", "1.6K EUR", "-40.5K EUR"."""
    whole = _half_up(Decimal(repr(float(amount))), 0)
    compact = compact_figure(float(whole))
    return f"{compact} {currency}" if compact else f"{amount:,.0f} {currency}"


def _value_figure(name: str, shown: str, low: str, high: str) -> str:
    return f'<div class="figure"><b>{_e(shown)}</b>{_e(name)}<span class="range">{_e(low)} to {_e(high)}</span></div>'


def _value(figures: ValueFigures | None) -> str:
    """The "Value" section: Hours saved, Value, Net value with their ranges, then the methodology line."""
    if figures is None:
        return f'<p class="missing">{VALUE_UNAVAILABLE}</p>'
    if figures.under_k is not None:
        return f'<p class="missing">{_e(VALUE_UNDER_K.format(k=figures.under_k))}</p>'
    if figures.runs == 0 and figures.units == 0 and figures.deliverables == 0:
        body = f'<p class="missing">No unit of work counted in the last {VALUE_WINDOW_DAYS} days.</p>'
    else:
        c = figures.currency
        hours = _value_figure(
            "Hours saved",
            _hours(figures.hours_saved),
            _hours(figures.hours_saved_range[0]),
            _hours(figures.hours_saved_range[1]),
        )
        value = _value_figure(
            "Value",
            _amount(figures.value, c),
            _amount(figures.value_range[0], c),
            _amount(figures.value_range[1], c),
        )
        if figures.cost_masked:
            net = f'<div class="figure"><b>{COST_HIDDEN}</b>Net value</div>'
        else:
            net = _value_figure(
                "Net value",
                _amount(figures.net_value, c),
                _amount(figures.net_value_range[0], c),
                _amount(figures.net_value_range[1], c),
            )
        counted = f"{_count(figures.runs)} {'run' if figures.runs == 1 else 'runs'}, {_count(figures.units)} " + (
            "unit of work" if figures.units == 1 else "units of work"
        )
        if figures.deliverables:
            counted += f", {_count(figures.deliverables)} " + (
                "chat deliverable" if figures.deliverables == 1 else "chat deliverables"
            )
        body = f'<div class="figures">{hours}{value}{net}</div><p class="dim">{_e(counted)}.</p>'
    return f'{body}<p class="method">{_e(VALUE_METHODOLOGY)}</p>'


def _prerequisites(lines: Sequence[PrerequisiteLine]) -> str:
    if not lines:
        return _missing()
    shown, hidden = _cap(lines, "prerequisites")
    marks = {True: ("ok", "Met"), False: ("ko", "Missing"), None: ("na", "To check")}
    rows = "".join(
        f'<li><span class="state {marks[p.met][0]}">{marks[p.met][1]}</span>{_e(plain_text(p.label, 110))}</li>'
        for p in shown
    )
    return f"<ul>{rows}{_more(hidden)}</ul>"


