def build_tools(
    token: str,
    executor: CallableToolExecutor,
    *,
    persist_file_fn: PersistFileFn | None = None,
    refresh_fn: RefreshFn | None = None,
    tenant_id: str = "",
    registered_version_fn: RegisteredVersionFn | None = None,
    **_kwargs: Any,
) -> list[ToolDefinition]:
    """Build OpenAEV integration tools.

    ``token`` is ``base_url||api_token`` (compound format).

    ``persist_file_fn`` (injected by ``integration_tools``) persists
    tool-generated bytes as a real downloadable attachment. Used by the
    reporting and document download actions; when absent the downloaded file
    stays in memory for the run, next to the document URL.

    ``refresh_fn`` (injected by ``integration_tools``) re-mints the auth token
    on a 401/403. For a platform-managed integration it re-issues the
    short-lived cross-platform JWT, which is what keeps a long autonomous run
    from 401-storming once the initial 10 min token expires (WS2). It is bound
    onto the shared headers so every REST call routed through ``_api`` recovers
    transparently; a static-API-key integration passes no callback and keeps
    the original single-shot behaviour.

    ``tenant_id`` (injected by ``integration_tools``) is the integration's
    optional Tenant field: the OpenAEV tenant every tool request goes to. Empty,
    the tenant is chosen from the caller's memberships (``_select_tenant``).
    """
    base_url, api_token = parse_compound_token(token, 2)
    # ``parse_compound_token`` does not normalise - strip whitespace and the
    # trailing slash exactly once so all downstream uses (REST endpoints,
    # ``[Open in OpenAEV](...)`` markdown links) compose cleanly. Strip the
    # token too so a ``base_url|| token`` value can't produce a malformed
    # ``Authorization: Bearer  <token>`` header that fails authentication.
    base_url = base_url.strip().rstrip("/")
    api_token = api_token.strip()
    headers = _headers(api_token, refresh_fn=refresh_fn)

    if not base_url:
        logger.debug(
            "OpenAEV base_url is empty - returning no tools. Edit the "
            "integration and ensure the base URL is set."
        )
        return []

    # One lazily-loaded settings snapshot per tool-set: resolves the default
    # tenant id (for the routes that exist only in tenant-scoped form) and the
    # enabled preview features (which gate whole modules behind a 404).
    capabilities = PlatformCapabilities(base_url, headers, configured_tenant_id=tenant_id)
    # Every module's requests scope themselves to the default tenant through
    # this one resolver (read by ``_scope_path``), so a new module cannot forget.
    headers.tenant_scope = capabilities
    # The caller's read rights (GET /api/me, once per tool set): OpenAEV answers an
    # empty page to a grant-limited identity, so the count reads say so (#1444).
    headers.read_scope = ReadScope(base_url, headers)

    tools: list[ToolDefinition] = []
    tools += register_core(base_url, headers, executor)
    tools += register_simulations(
        base_url, headers, executor, persist_file_fn=persist_file_fn
    )
    tools += register_injects(base_url, headers, executor)
    tools += register_expectations(base_url, headers, executor)
    tools += register_testing(base_url, headers, executor)
    tools += register_assets(base_url, headers, executor)
    tools += register_teams(base_url, headers, executor)
    tools += register_access(base_url, headers, executor)
    tools += register_content(base_url, headers, executor, persist_file_fn=persist_file_fn)
    tools += register_phishing(base_url, headers, executor)
    tools += register_lessons_reports(
        base_url, headers, executor, persist_file_fn=persist_file_fn
    )
    tools += register_taxonomy(base_url, headers, executor)
    tools += register_findings(base_url, headers, executor)
    tools += register_threat_arsenal(
        base_url, headers, executor, capabilities=capabilities
    )
    tools += register_dashboards(base_url, headers, executor)
    tools += register_notifications(base_url, headers, executor)
    tools += register_preview(base_url, headers, executor, capabilities=capabilities)
    tools += register_platform(
        base_url,
        headers,
        executor,
        capabilities=capabilities,
        registered_version_fn=registered_version_fn,
    )
    tools += register_autonomous(base_url, headers, executor)
    tools += register_health_reads(base_url, headers, executor)
    # An 8-hex id prefix is answered by OpenAEV as a missing object ("Inject not
    # found"): refuse it by name before any request (app.integrations.short_id).
    install_short_id_guard(executor, [tool.name for tool in tools], platform="OpenAEV")
    return tools
