"""OpenAEV integration provider package.

Comprehensive management of an OpenAEV (Adversarial Exposure Validation /
Breach & Attack Simulation) platform via its REST API.

The provider is split by domain:

* ``_common``          - shared HTTP headers, search-body builder, filters,
                         UI-link helper, enums, and entity formatters.
* ``core``             - the original tool set (assets, teams, scenarios,
                         payloads, injects, atomic testing, findings,
                         reference data, exercises) - relocated unchanged.
* ``simulations``      - simulation (exercise) lifecycle + execution and
                         scenario lifecycle (launch/recurrence/import/export).
* ``injects``          - injects (CRUD + execution).
* ``expectations``     - expectation results: the scored verdict on the
                         security controls (simulation results, ATT&CK
                         breakdown, per-target rows, drift, manual validation).
* ``threat_arsenal``   - Threat Arsenal actions (the v3 payload surface).
* ``dashboards``       - ad-hoc analytics queries + custom dashboards/widgets.
* ``notifications``    - notifiers, notification triggers, per-user inbox.
* ``preview``          - feature-flagged surfaces (attack path, chaining) that
                         answer 404 when their flag is off.
* ``testing``          - atomic testing + payload management.
* ``assets``           - endpoints, asset groups, security platforms (writes).
* ``teams``            - teams + players (writes).
* ``access``           - organizations, users/groups/roles (tenant + platform
                         EE) and the authenticated user profile.
* ``content``          - documents, channels, articles, challenges.
* ``phishing``         - phishing landing pages + email templates (Components).
* ``lessons_reports``  - lessons learned + reports.
* ``taxonomy``         - tags, kill chain phases, attack patterns, variables.
* ``findings``         - findings + vulnerabilities (writes).
* ``platform``         - connectors (read) + platform settings.
* ``health_reads``     - read-only module health reads of the Platform Health
                         module checker (#101 S15b-2c).

Token format passed by the dispatcher: ``base_url||api_token`` (the
``extra_config`` base_url is prepended by ``_get_token`` in
``integration_tools.py``).
"""

