"""The STIX extraction emits only relationships OpenCTI's schema accepts.

OpenCTI's import connectors drop a relationship its schema does not take between two
entity types, without a word: an extraction whose ontology drifts from the schema loses
knowledge silently. Every (kind, verb, kind) the ontology can produce, read in either
direction, is checked against a snapshot of the schema
(``fixtures/extraction/opencti_relationship_schema.json``, regenerated by
``scripts/stix_opencti_relationship_schema.py``), and every indicator relationship the
bundle writes against it too.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

import pytest

from app.services.stix_extraction.bundle import ExtractedObject, ExtractedRelation, build_bundle
from app.services.stix_extraction.ontology import (
    DERIVED_KINDS,
    LLM_KINDS,
    PATTERN_KINDS,
    RELATION_TYPES,
    resolve_relation,
    resolve_triple,
)

_SCHEMA = json.loads((Path(__file__).parent / "fixtures/extraction/opencti_relationship_schema.json").read_text())
_ALLOWED = {tuple(triple) for triple in _SCHEMA["allowed"]}

# Extraction kind → the kind the snapshot names (one STIX object type for several kinds).
_SCHEMA_KIND = {
    "attack-pattern-id": "attack-pattern",
    "cve": "vulnerability",
    "file-name": "file",
    "md5": "file",
    "sha1": "file",
    "sha256": "file",
    "sha512": "file",
    "product": "software",
}
_KINDS = [k for k in (*LLM_KINDS, *DERIVED_KINDS, *PATTERN_KINDS) if k != "unknown"]
# Kinds the snapshot does not cover: their relationships must stay none.
_UNCOVERED = {"mac-addr", "autonomous-system", "windows-registry-key"}


def _schema_kind(kind: str) -> str:
    return _SCHEMA_KIND.get(kind, kind)


def _produced() -> set[tuple[str, str, str]]:
    triples = set()
    for source in _KINDS:
        for target in _KINDS:
            for verb in (*RELATION_TYPES, "related-to"):
                resolved = resolve_triple(source, verb, target)
                if resolved is None:
                    continue
                kept, swapped = resolved
                ends = (target, source) if swapped else (source, target)
                triples.add((ends[0], kept, ends[1]))
    return triples


def test_every_relationship_the_ontology_produces_is_one_opencti_accepts():
    refused = sorted(
        (source, verb, target)
        for source, verb, target in _produced()
        if verb not in ("indicates", "related-to")  # an indicator's; any pair (OpenCTI's fallback)
        and (_schema_kind(source), verb, _schema_kind(target)) not in _ALLOWED
    )
    assert refused == []


def test_kinds_the_schema_snapshot_does_not_cover_are_never_linked():
    # related-to excepted: OpenCTI accepts it between any two objects.
    assert not [t for t in _produced() if (t[0] in _UNCOVERED or t[2] in _UNCOVERED) and t[1] != "related-to"]


def test_an_indicates_relationship_targets_what_an_indicator_may_indicate():
    for source, verb, target in _produced():
        if verb == "indicates":
            assert ("indicator", "based-on", _schema_kind(source)) in _ALLOWED, source
            assert ("indicator", "indicates", _schema_kind(target)) in _ALLOWED, target


@pytest.mark.parametrize(
    ("source", "verb", "target", "expected"),
    [
        # OpenCTI names a malware's author, and a person's country, its own way.
        ("malware", "attributed-to", "intrusion-set", ("authored-by", False)),
        ("threat-actor", "originates-from", "country", ("located-at", False)),
        ("threat-actor", "located-at", "country", ("located-at", False)),
        ("intrusion-set", "located-at", "country", ("originates-from", False)),
        # A malware's network contacts and files.
        ("malware", "uses", "domain-name", ("communicates-with", False)),
        ("malware", "uses", "file-name", ("drops", False)),
        ("malware", "communicates-with", "infrastructure", ("beacons-to", False)),
        # A threat "using" a sample or an address is what that observable indicates.
        ("tool", "uses", "sha256", ("indicates", True)),
        ("intrusion-set", "uses", "domain-name", ("indicates", True)),
        ("sha256", "indicates", "malware", ("indicates", False)),
        # Only allowed the other way round: read the other way.
        ("vulnerability", "exploits", "malware", ("exploits", True)),
        ("country", "located-at", "organization", ("located-at", True)),
        # Refused: no place inside a smaller one, no address resolving to a domain,
        # no group attributed to another group.
        ("country", "located-at", "city", None),
        ("ipv4-addr", "resolves-to", "domain-name", None),
        ("intrusion-set", "attributed-to", "intrusion-set", None),
    ],
)
def test_resolve_triple(source, verb, target, expected):
    assert resolve_triple(source, verb, target) == expected


def test_resolve_relation_keeps_only_relationships_read_as_given():
    assert resolve_relation("tool", "uses", "sha256") is None
    assert resolve_relation("malware", "uses", "domain-name") == "communicates-with"


def _bundle(objects, relations):
    return build_bundle(objects, relations, document_name="r", include_report=False, now=datetime(2026, 1, 1, tzinfo=UTC))


def _relationships(bundle):
    by_id = {o["id"]: o for o in bundle["objects"]}
    return {
        (by_id[o["source_ref"]]["type"], o["relationship_type"], by_id[o["target_ref"]]["type"])
        for o in bundle["objects"]
        if o["type"] == "relationship"
    }


def test_an_observable_tied_to_a_threat_is_written_as_an_indicator_of_it():
    bundle = _bundle(
        [
            ExtractedObject("A1", "malware", "Emotet"),
            ExtractedObject("A2", "ipv4-addr", "45.77.1.2", value="45.77.1.2"),
            ExtractedObject("A3", "sha256", "a" * 64, value="a" * 64),
        ],
        [
            ExtractedRelation("A1", "communicates-with", "A2", ["Emotet connects to 45.77.1.2"]),
            ExtractedRelation("A3", "indicates", "A1"),
        ],
    )
    indicators = [o for o in bundle["objects"] if o["type"] == "indicator"]
    assert sorted(i["pattern"] for i in indicators) == [
        "[file:hashes.'SHA-256' = '" + "a" * 64 + "']",
        "[ipv4-addr:value = '45.77.1.2']",
    ]
    assert {i["x_opencti_main_observable_type"] for i in indicators} == {"IPv4-Addr", "StixFile"}
    assert _relationships(bundle) == {
        ("malware", "communicates-with", "ipv4-addr"),
        ("indicator", "based-on", "ipv4-addr"),
        ("indicator", "based-on", "file"),
        ("indicator", "indicates", "malware"),
    }
    # An observable "indicates" only through its indicator, and keeps its evidence there.
    indicates = [o for o in bundle["objects"] if o.get("relationship_type") == "indicates"]
    assert any(o.get("description") == "Emotet connects to 45.77.1.2" for o in indicates)


def test_every_relationship_the_bundle_writes_is_one_opencti_accepts():
    bundle = _bundle(
        [
            ExtractedObject("A1", "malware", "Emotet"),
            ExtractedObject("A2", "domain-name", "evil.example", value="evil.example"),
            ExtractedObject("A3", "file-name", "stage2.dll", value="stage2.dll"),
            ExtractedObject("A4", "intrusion-set", "TA542"),
            ExtractedObject("A5", "threat-actor", "Ivan"),
            ExtractedObject("A6", "country", "Russia", code="RU"),
        ],
        [
            ExtractedRelation("A1", "communicates-with", "A2"),
            ExtractedRelation("A1", "drops", "A3"),
            ExtractedRelation("A1", "authored-by", "A4"),
            ExtractedRelation("A2", "indicates", "A4"),
            ExtractedRelation("A5", "located-at", "A6"),
        ],
    )
    stix_kind = {"location": "country"}
    for source, verb, target in _relationships(bundle):
        triple = (stix_kind.get(source, source), verb, stix_kind.get(target, target))
        assert triple in _ALLOWED, triple


def test_a_threat_actor_is_written_as_an_individual():
    bundle = _bundle([ExtractedObject("A1", "threat-actor", "Ivan")], [])
    actor = bundle["objects"][0]
    assert actor["resource_level"] == "individual"
    assert actor["x_opencti_type"] == "Threat-Actor-Individual"
    from pycti import ThreatActorIndividual

    assert actor["id"] == ThreatActorIndividual.generate_id("Ivan")


def test_a_place_is_targeted_by_a_threat_never_by_a_technique() -> None:
    """A technique targets what it acts on (an identity, a vulnerability); a victim's country
    is targeted by the actor, the malware or the campaign. No gold records a technique
    targeting a place: such a link is not read, either way round."""
    from app.services.stix_extraction.ontology import resolve_triple

    for place in ("country", "region", "city"):
        assert resolve_triple("attack-pattern", "targets", place) is None, place
        assert resolve_triple(place, "targets", "attack-pattern") is None, place
        assert resolve_triple("intrusion-set", "targets", place) == ("targets", False), place
    assert resolve_triple("attack-pattern", "targets", "cve") == ("targets", False)
