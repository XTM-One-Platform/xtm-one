/** The names the pane draws; agentIcons.test.ts holds them equal to the web `ICON_MAP`. */
export const AGENT_ICON_NAMES: readonly string[] = Object.keys(AGENT_ICONS);

export const renderAgentIcon: ChatAgentIconRenderer = (name, { size }) => {
  const Icon = Object.prototype.hasOwnProperty.call(AGENT_ICONS, name) ? AGENT_ICONS[name] : undefined;
  return Icon ? <Icon size={size} aria-hidden="true" data-agent-icon={name} /> : null;
};
