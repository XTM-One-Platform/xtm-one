type LabelledValue = keyof typeof OBJECT_VALUE_LABELS;

function isLabelled(value: string): value is LabelledValue {
  return Object.prototype.hasOwnProperty.call(OBJECT_VALUE_LABELS, value);
}

/** A file's content type in a word: its format ("image/png" is "PNG", "image/svg+xml" is "SVG", "application/vnd.ms-excel" is "MS-EXCEL"). */
function contentTypeWord(value: string): string {
  const format = value.slice(value.indexOf("/") + 1).split("+")[0].trim();
  const last = format.split(".").filter(Boolean).pop() ?? format;
  return last.replace(/^x-/, "").toUpperCase();
}

/** A stored code in words: underscores and dashes as spaces, the first letter upper case. */
function humanise(value: string): string {
  const words = value.replace(/[_-]+/g, " ").trim();
  return words ? words.charAt(0).toUpperCase() + words.slice(1) : value;
}

/**
 * One stored state or kind as the reader reads it: the catalog label through
 * `translate` (the page's `t_i18n`), else a content type's format, else the
 * code humanised.
 */
export function objectValueText(value: string, translate: (id: string) => string): string {
  if (isLabelled(value)) return translate(OBJECT_VALUE_LABELS[value]);
  // A file a channel or an agent account stored: `channel:<channel>`, `account:<provider>`.
  if (value.startsWith("channel:")) return objectValueText(value.slice("channel:".length), translate);
  if (value.startsWith("account:")) return translate(OBJECT_VALUE_LABELS.agent_account);
  if (/^[a-z]+\/[^\s/;]+$/i.test(value)) return contentTypeWord(value);
  return humanise(value);
}
