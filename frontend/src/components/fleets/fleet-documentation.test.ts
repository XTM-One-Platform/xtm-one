// The fleet About view's pure parts (#9174, slice 6b; #9768 S2): section
// titles, the sections a reader sees and a refused regenerate.
import { test } from "vitest";
import assert from "node:assert/strict";

import type { FleetDocumentation } from "@/hooks/api/useFleetApi";

import { authorKind, exportRefusal, regenerateRefusal, restoredLabel, sectionTitle, versionAuthorLabel, writtenSections } from "./fleet-documentation";

const t = (text: string, values?: Record<string, string | number>) =>
  `t:${values ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k])) : text}`;

const doc: Pick<FleetDocumentation, "section_keys" | "sections"> = {
  section_keys: ["purpose", "use_case", "flow", "outcomes"],
  sections: { purpose: "Why it exists", flow: "  ", outcomes: "What it produces" },
};

test("a known section reads its catalog title, an unknown one its key", () => {
  assert.equal(sectionTitle("purpose", t), "t:Purpose");
  assert.equal(sectionTitle("roi_units", t), "t:Unit of work");
  assert.equal(sectionTitle("brand_new", t), "brand_new");
});

test("the reader sees the written sections only, in the API's order", () => {
  assert.deepEqual(writtenSections(doc), [
    { key: "purpose", text: "Why it exists" },
    { key: "outcomes", text: "What it produces" },
  ]);
});

test("a refused regenerate reads one sentence per status, never the server's raw text", () => {
  assert.match(regenerateRefusal({ status: 409 }, t), /changed since this page opened/);
  assert.match(regenerateRefusal({ status: 422 }, t), /could not generate this/);
  assert.match(regenerateRefusal({ status: 500 }, t), /could not be generated/);
  assert.match(regenerateRefusal(new Error("boom"), t), /could not be generated/);
});

test("who wrote it: the platform, a fork, or a person", () => {
  assert.equal(authorKind(null), null);
  assert.equal(authorKind("seed"), "seed");
  assert.equal(authorKind("fork"), "fork");
  assert.equal(authorKind("7c1f0000-0000-4000-8000-000000000000"), "person");
});

test("a failed datasheet export names its reason and what to do (UX round 1 B1)", () => {
  assert.match(exportRefusal({ status: 429 }, t), /Too many exports/);
  assert.match(exportRefusal({ status: 404 }, t), /no documentation yet/);
  assert.match(exportRefusal({ status: 503 }, t), /could not be rendered/);
  assert.match(exportRefusal(new Error("network"), t), /Try the export again/);
});

test("the version history names each version's author: Filigran, a fork or AI", () => {
  assert.equal(versionAuthorLabel("seed"), "Written by Filigran");
  assert.equal(versionAuthorLabel("fork"), "Copied from the original fleet");
  assert.equal(versionAuthorLabel("person"), "Generated by AI");
  assert.equal(versionAuthorLabel(null), "Generated by AI");
});

test("a restored version names the version brought back and its text's author, never 'Generated by AI'", () => {
  assert.equal(restoredLabel({ version: null, author: "seed" }, t), "t:Restored from the shipped version, written by Filigran");
  assert.equal(restoredLabel({ version: 1, author: "seed" }, t), "t:Restored from version 1, written by Filigran");
  assert.equal(restoredLabel({ version: 1, author: "fork" }, t), "t:Restored from version 1, copied from the original fleet");
  assert.equal(restoredLabel({ version: 2, author: "ai" }, t), "t:Restored from version 2, generated by AI");
});
