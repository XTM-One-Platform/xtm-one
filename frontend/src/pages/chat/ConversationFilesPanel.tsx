/**
 * ConversationFilesPanel — right-hand slide-over listing every file in a
 * conversation.
 *
 * Both directions in one place: attachments the user sent, and artifacts the
 * agent produced via ``generate_file``. Previously either could only be reached
 * by scrolling the transcript back to the message carrying its chip, which does
 * not survive a long investigation.
 *
 * Two access paths converge here:
 *
 *   * The conversation's **owner** — opens straight into the list.
 *   * A non-owner **administrator** — the listing 403s with
 *     ``confidentiality_acknowledgement_required`` until they pass the
 *     break-glass gate (:file:`ConfidentialityGateDialog.tsx`). The withholding
 *     happens server-side: no filename is returned until the acknowledgement is
 *     recorded, so the dialog is the explanation for a refusal that has already
 *     happened rather than the thing enforcing it.
 *
 * Visual language is deliberately shared with the inline transcript chips via
 * ``fileVisuals.ts`` — same icon, colour and size formatting — so a file reads
 * as the same file in both places.
 */

import { useCallback, useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import {
  AlertTriangle,
  ArrowUpRight,
  BookPlus,
  Bot,
  Download,
  FolderOpen,
  MessageSquareDashed,
  ShieldAlert,
  Upload,
  X,
} from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { SegmentedFilter } from "@/components/ui/segmented-filter";
import { SlideOver } from "@/components/ui/slide-over";
import { Tip } from "@/components/ui/tooltip";
import { useToast } from "@/components/ui/toast";
import { useAddWorkspaceSourceFromAttachment, useWorkspace } from "@/hooks/api/useWorkspaceApi";
import { useAiActionDisabled } from "@/hooks/useAiDisabled";
import { AiDisabledTip } from "@/components/ui/ai-disabled";
import { useFormatter } from "@/i18n";
import {
  isConfidentialityAckRequired,
  useAcknowledgeConversationFileAccess,
  useConversationFiles,
} from "@/hooks/api/useChatApi";
import { ConfidentialityGateDialog } from "@/pages/chat/ConfidentialityGateDialog";
import { downloadErrorDescription } from "@/lib/download-error";
import {
  authenticatedDownload,
  extensionFromFilename,
  formatFileSize,
  mimeLabel,
  mimeVisual,
  resolveAttachmentMime,
} from "@/pages/chat/fileVisuals";
import { cn, formatShortDateTime } from "@/lib/utils";
import type { ConversationFile, ConversationFileOrigin } from "@/types";
import { Spinner } from "@filigran/design-system";

type OriginFilter = "all" | ConversationFileOrigin;

interface ConversationFilesPanelProps {
  conversationId: string | null;
  conversationTitle?: string | null;
  open: boolean;
  onClose: () => void;
  /**
   * Scroll the transcript to a message. Omit to hide the jump affordance
   * entirely (e.g. if a caller renders the panel outside a transcript view).
   */
  onJumpToMessage?: (messageId: string) => void;
  /** The workspace the conversation is filed in: its managers can add
   *  a file to the workspace's sources from here. */
  workspaceId?: string | null;
}

/** Origin badge — states plainly whether the user or the agent put the file here. */
function OriginBadge({ origin }: { origin: ConversationFileOrigin }) {
  const { t_i18n } = useFormatter();
  if (origin === "uploaded") {
    return (
      <Badge variant="outline" className="h-4 gap-1 px-1.5 text-[9px] font-medium">
        <Upload className="h-2.5 w-2.5" />
        {t_i18n("Uploaded")}
      </Badge>
    );
  }
  if (origin === "generated") {
    return (
      <Badge variant="cyan" className="h-4 gap-1 px-1.5 text-[9px] font-medium">
        <Bot className="h-2.5 w-2.5" />
        {t_i18n("Generated by agent")}
      </Badge>
    );
  }
  // ``other`` is surfaced rather than hidden: an unmapped ``source`` should be
  // visibly unclassified, not silently presented as one of the two known kinds.
  return (
    <Badge variant="outline" className="h-4 px-1.5 text-[9px] font-medium">
      {t_i18n("Other")}
    </Badge>
  );
}

function FileRow({
  file,
  onJumpToMessage,
  onAddToWorkspace,
}: {
  file: ConversationFile;
  onJumpToMessage?: (messageId: string) => void;
  /** Present for a manager of the conversation's workspace. */
  onAddToWorkspace?: (file: ConversationFile) => void;
}) {
  // Adding a source embeds it: an AI action (FR-018).
  const aiOff = useAiActionDisabled();
  const { t_i18n } = useFormatter();
  const { toast } = useToast();
  const [downloading, setDownloading] = useState(false);

  // ``type`` is not part of the files payload (unlike message attachments), so
  // derive the short label from the filename and let ``content_type`` win.
  const visualLike = useMemo(
    () => ({
      content_type: file.content_type,
      type: extensionFromFilename(file.filename),
    }),
    [file.content_type, file.filename],
  );
  const mime = resolveAttachmentMime(visualLike);
  const { icon: Icon, color } = mimeVisual(mime);
  const typeLabel = mimeLabel(visualLike, mime);
  const sizeLabel = formatFileSize(file.size);

  const handleDownload = useCallback(async () => {
    setDownloading(true);
    try {
      await authenticatedDownload(file.download_url, file.filename);
    } catch (err) {
      toast({
        variant: "error",
        title: t_i18n("Download failed"),
        description: downloadErrorDescription(err, file.filename, t_i18n),
      });
    } finally {
      setDownloading(false);
    }
  }, [file.download_url, file.filename, t_i18n, toast]);

  return (
    <div className="group flex items-start gap-2.5 rounded-sm border border-elevation-subtle-soft layer-1 bg-elevation-default px-2.5 py-2 transition-colors hover:border-accent/30">
      <Icon className={cn("mt-0.5 h-4 w-4 shrink-0", color)} />

      <div className="min-w-0 flex-1">
<Tip content={file.filename}>
  <div className="truncate content-compact font-medium">{file.filename}</div>
</Tip>
        <div className="mt-1 flex flex-wrap items-center gap-1.5">
          <OriginBadge origin={file.origin} />
          <span className="content-caption text-default-secondary">{typeLabel}</span>
          {sizeLabel && (
            <>
              <span className="content-caption text-default-disabled">·</span>
              <span className="content-caption text-default-secondary">{sizeLabel}</span>
            </>
          )}
          <span className="content-caption text-default-disabled">·</span>
          <span className="content-caption text-default-secondary">
            {formatShortDateTime(file.created_at)}
          </span>
        </div>
      </div>

      <div className="flex shrink-0 items-center gap-0.5">
        {/* Hidden when ``message_id`` is null — the linkage may never have been
            established, or was dropped (it is ON DELETE SET NULL). Better no
            affordance than one that scrolls nowhere. */}
        {file.message_id && onJumpToMessage && (
          <Tip content={t_i18n("Show in conversation")}>
            <button
              type="button"
              onClick={() => onJumpToMessage(file.message_id as string)}
              aria-label={t_i18n("Show in conversation")}
              className="rounded-sm p-1.5 text-default-secondary transition-colors hover:bg-elevation-hover hover:text-default-primary"
            >
              <MessageSquareDashed className="h-3.5 w-3.5" />
            </button>
          </Tip>
        )}
        {onAddToWorkspace && (
          <AiDisabledTip>
          <Tip content={t_i18n("Add to the workspace's sources")}>
            <button
              type="button"
              disabled={aiOff}
              onClick={() => onAddToWorkspace(file)}
              aria-label={t_i18n("Add {filename} to the workspace's sources", { filename: file.filename })}
              className="rounded-sm p-1.5 text-default-secondary transition-colors hover:bg-elevation-hover hover:text-default-primary disabled:opacity-50"
            >
              <BookPlus className="h-3.5 w-3.5" />
            </button>
          </Tip>
          </AiDisabledTip>
        )}
<Tip content={t_i18n("Download")} wrap>
          <button
            type="button"
            onClick={handleDownload}
            disabled={downloading}
            aria-label={t_i18n("Download {filename}", { filename: file.filename })}
            className="rounded-sm p-1.5 text-default-secondary transition-colors hover:bg-elevation-hover hover:text-default-primary disabled:opacity-50"
          >
            {downloading && <Spinner size="sm" tone="inherit" />}{!downloading && <Download className="h-3.5 w-3.5" />}
          </button>
        </Tip>
      </div>
    </div>
  );
}

export function ConversationFilesPanel({
  conversationId,
  conversationTitle,
  open,
  onClose,
  onJumpToMessage,
  workspaceId = null,
}: ConversationFilesPanelProps) {
  const { t_i18n } = useFormatter();
  const { toast } = useToast();
  const workspace = useWorkspace(open ? workspaceId : null);
  const addSource = useAddWorkspaceSourceFromAttachment();
  const addToWorkspace = useCallback(
    (file: ConversationFile) => {
      if (!workspaceId) return;
      addSource.mutate(
        { id: workspaceId, fileAttachmentId: file.id },
        {
          onSuccess: () =>
            toast({ title: t_i18n("{name} added to the workspace's sources", { name: file.filename }), variant: "success" }),
          onError: (err) =>
            toast({ title: t_i18n("The file could not be added"), description: err.message, variant: "error" }),
        },
      );
    },
    [workspaceId, addSource, toast, t_i18n],
  );
  const [filter, setFilter] = useState<OriginFilter>("all");
  const [gateDismissed, setGateDismissed] = useState(false);

  const {
    data,
    isLoading,
    error,
    refetch,
  } = useConversationFiles(conversationId, {
    enabled: open,
    origin: filter === "all" ? undefined : filter,
  });

  const ackMutation = useAcknowledgeConversationFileAccess(conversationId);

  const needsAcknowledgement = isConfidentialityAckRequired(error);

  // Reset per-conversation view state. Without this, the filter and a previous
  // dismissal would leak across conversations — and a dismissed gate would keep
  // a *different* conversation's panel looking permanently empty.
  useEffect(() => {
    setFilter("all");
    setGateDismissed(false);
  }, [conversationId]);

  // Re-arm the gate each time the panel is reopened, so an admin who dismissed
  // it earlier is asked again rather than silently seeing nothing.
  useEffect(() => {
    if (open) setGateDismissed(false);
  }, [open]);

  const handleAcknowledge = useCallback(() => {
    ackMutation.mutate(undefined, {
      // The hook invalidates the files query on success; refetch explicitly so
      // the list populates even if the query had settled into an error state
      // (invalidating an errored query does not always re-run it).
      onSuccess: () => {
        void refetch();
      },
    });
  }, [ackMutation, refetch]);

  if (!open) return null;

  const files = data?.files ?? [];
  const viaBreakGlass = data?.via_break_glass ?? false;

  const filterOptions: { key: OriginFilter; label: string }[] = [
    { key: "all", label: t_i18n("All") },
    { key: "uploaded", label: t_i18n("Uploaded") },
    { key: "generated", label: t_i18n("Generated") },
  ];

  return (
    <>
      <SlideOver open onClose={onClose} label={t_i18n("Conversation files")}>
          {/* Header */}
          <div className="flex items-start gap-3 border-b border-elevation-subtle p-4">
            <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-sm bg-accent/10">
              <FolderOpen className="h-[18px] w-[18px] text-accent" />
            </div>
            <div className="min-w-0 flex-1">
              <h3 className="content-base font-semibold">{t_i18n("Conversation files")}</h3>
              <p className="mt-0.5 content-caption text-default-secondary">
                {isLoading
                  ? t_i18n("Loading…")
                  : needsAcknowledgement
                    ? t_i18n("Access requires acknowledgement")
                    : t_i18n("{count} of {total, plural, one {# file} other {# files}}", {
                        count: files.length,
                        total: data?.total ?? 0,
                      })}
              </p>
            </div>
            {/* The same files, in the cross-context repository (Work > Files),
                scoped to this conversation. Hidden on a break-glass session:
                the repository deliberately has no admin-wide read, so
                the link would land the admin on an empty, confusing scope. */}
            {conversationId && !viaBreakGlass && !needsAcknowledgement && (
              <Tip content={t_i18n("Open in Files")}>
                <Link
                  to={`/files?conversation=${encodeURIComponent(conversationId)}`}
                  onClick={onClose}
                  aria-label={t_i18n("Open in Files")}
                  className="shrink-0 rounded-sm p-1 text-default-secondary transition-colors hover:bg-elevation-hover hover:text-default-primary"
                >
                  <ArrowUpRight className="h-4 w-4" />
                </Link>
              </Tip>
            )}
            <button
              type="button"
              onClick={onClose}
              aria-label={t_i18n("Close")}
              className="shrink-0 rounded-sm p-1 text-default-secondary transition-colors hover:bg-elevation-hover hover:text-default-primary"
            >
              <X className="h-4 w-4" />
            </button>
          </div>

          {/* Standing reminder for break-glass sessions — the gate is a moment,
              this is the whole time the panel is open. */}
          {viaBreakGlass && (
            <div className="flex items-start gap-2 border-b border-feedback-alert-primary/20 bg-feedback-alert-primary/5 px-4 py-2">
              <ShieldAlert className="mt-0.5 h-3.5 w-3.5 shrink-0 text-feedback-warning-primary" />
              <p className="content-caption leading-relaxed text-default-secondary">
                {t_i18n(
                  "You are viewing another user's files as an administrator. This access is recorded in the audit trail.",
                )}
              </p>
            </div>
          )}

          {/* Filter */}
          {!needsAcknowledgement && (
            <div className="border-b border-elevation-subtle-soft px-4 py-2">
              <SegmentedFilter
                options={filterOptions}
                value={filter}
                onChange={setFilter}
                ariaLabel={t_i18n("Filter files by origin")}
              />
            </div>
          )}

          {/* Body */}
          <div className="min-h-0 flex-1 overflow-y-auto p-4">
            {isLoading ? (
              <div className="flex items-center justify-center gap-2 py-12 content-compact text-default-secondary">
                <Spinner size="sm" tone="inherit" />
                {t_i18n("Loading files…")}
              </div>
            ) : needsAcknowledgement ? (
              // The gate dialog carries the explanation; this is the state the
              // panel sits in behind it (and after a cancel).
              <div className="flex flex-col items-center gap-3 py-12 text-center">
                <ShieldAlert className="h-8 w-8 text-feedback-warning-primary" />
                <p className="max-w-[260px] content-compact leading-relaxed text-default-secondary">
                  {t_i18n(
                    "These files belong to another user. Acknowledge the confidentiality notice to view them.",
                  )}
                </p>
                <Button size="sm" variant="secondary" onClick={() => setGateDismissed(false)}>
                  {t_i18n("Review notice")}
                </Button>
              </div>
            ) : error ? (
              <div className="flex flex-col items-center gap-3 py-12 text-center">
                <AlertTriangle className="h-8 w-8 text-feedback-error-primary/60" />
                <p className="max-w-[260px] content-compact leading-relaxed text-default-secondary">
                  {error.message || t_i18n("The files could not be loaded.")}
                </p>
                <Button size="sm" variant="secondary" onClick={() => void refetch()}>
                  {t_i18n("Retry")}
                </Button>
              </div>
            ) : files.length === 0 ? (
              <div className="flex flex-col items-center gap-2 py-12 text-center">
                <FolderOpen className="h-8 w-8 text-default-disabled" />
                <p className="content-compact font-medium">
                  {filter === "all"
                    ? t_i18n("No files in this conversation yet")
                    : t_i18n("No files match this filter")}
                </p>
                <p className="max-w-[260px] content-caption leading-relaxed text-default-secondary">
                  {filter === "all"
                    ? t_i18n(
                        "Files you attach and files the agent generates will appear here.",
                      )
                    : t_i18n("Try a different origin filter.")}
                </p>
              </div>
            ) : (
              <div className="space-y-1.5">
                {files.map((f) => (
                  <FileRow
                    key={f.id}
                    file={f}
                    onJumpToMessage={onJumpToMessage}
                    onAddToWorkspace={workspace.data?.can_manage && !workspace.data.is_archived ? addToWorkspace : undefined}
                  />
                ))}
              </div>
            )}

            {/* The listing is paginated server-side; say so rather than
                silently presenting a truncated set as complete. */}
            {!needsAcknowledgement &&
              !error &&
              files.length > 0 &&
              (data?.total ?? 0) > files.length && (
                <p className="pt-3 text-center content-caption text-default-secondary">
                  {t_i18n("Showing the {count} most recent of {total} files.", {
                    count: files.length,
                    total: data?.total ?? 0,
                  })}
                </p>
              )}
          </div>
      </SlideOver>

      <ConfidentialityGateDialog
        open={needsAcknowledgement && !gateDismissed}
        conversationTitle={conversationTitle}
        pending={ackMutation.isPending}
        error={ackMutation.error?.message ?? null}
        onCancel={() => setGateDismissed(true)}
        onAcknowledge={handleAcknowledge}
      />
    </>
  );
}
